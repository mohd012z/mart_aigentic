def guide(kind):
    """Return the deep-dive guide for a menu action, or None if unknown."""
    body = _BODIES.get(kind)
    if not body:
        return None
    label = ACTIONS.get(kind, (kind,))[0]
    return "Selected: " + label + " — deep dive\n\n" + body


def all_guide_kinds():
    return sorted(_BODIES)
